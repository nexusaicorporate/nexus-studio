import os
import glob

PROMPT_LISTS_DIR = os.path.join(os.path.dirname(__file__), '..', 'LTXV-PromptGen', 'LTXV-PromptLists')
OUTPUT_FILE = os.path.join(os.path.dirname(__file__), '..', 'supabase', 'seed.sql')

def escape_sql(text):
    return text.replace("'", "''")

def main():
    if not os.path.exists(PROMPT_LISTS_DIR):
        print(f"Directory not found: {PROMPT_LISTS_DIR}")
        return

    txt_files = glob.glob(os.path.join(PROMPT_LISTS_DIR, '*.txt'))
    
    if not txt_files:
        print("No text files found.")
        return

    sql_statements = [
        "-- ==========================================",
        "-- Recipes Seed Data for Prompt Director",
        "-- Auto-generated by scripts/generate_recipes_seed.py",
        "-- ==========================================\n"
    ]

    for file_path in txt_files:
        filename = os.path.basename(file_path)
        # Convert 'LTXV-science-fiction-scenes.txt' to 'science-fiction-scenes'
        category = filename.replace('LTXV-', '').replace('.txt', '')

        with open(file_path, 'r', encoding='utf-8') as f:
            lines = f.readlines()
            
        for line in lines:
            line = line.strip()
            if not line:
                continue
            
            content_escaped = escape_sql(line)
            category_escaped = escape_sql(category)
            
            sql = f"INSERT INTO public.recipes (category, content) VALUES ('{category_escaped}', '{content_escaped}');"
            sql_statements.append(sql)

    # Ensure supabase directory exists
    os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
    
    with open(OUTPUT_FILE, 'w', encoding='utf-8') as f:
        f.write('\n'.join(sql_statements))
        f.write('\n')

    print(f"Generated {OUTPUT_FILE} with {len(sql_statements) - 4} recipe entries.")

if __name__ == '__main__':
    main()
